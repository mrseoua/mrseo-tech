function mrseo_ua_semantic_current(){
 if(mrseo_locale()!=='uk')return null;
 $entry=mrseo_i18n_current_entry();
 if(!$entry)return null;
 return mrseo_ua_semantic_map()[$entry['slug']]??null;
}
function mrseo_ua_semantic_copy($slug,$data){
 if(!$data||mrseo_locale()!=='uk')return $data;
 $m=mrseo_ua_semantic_map()[$slug]??null;
 if(!$m)return $data;
 foreach(array('lead','sectionTitle') as $field)if(isset($m[$field]))$data[$field]=$m[$field];
 if(isset($m['faqQuestion'])){
  $i=$m['faqQuestion'][0];
  if(isset($data['faq'][$i])){ $data['faq'][$i][0]=$m['faqQuestion'][1]; if(isset($m['faqAnswer']))$data['faq'][$i][1]=$m['faqAnswer']; }
 }
 if(isset($m['related'])){
  $related=$data['related']??array();
  foreach($m['related'] as $link)if(!in_array($link[0],array_column($related,0),true))$related[]=$link;
  $data['related']=$related;
 }
 if(isset($data['related']))$data['related']=array_values(array_filter($data['related'],static fn($link)=>!isset(mrseo_ua_retired_services()[$link[0]])&&$link[0]!==$slug));
 return $data;
}
